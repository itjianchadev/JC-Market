// Render imports/golive-credentials.json → a printable PDF hand-out, grouped by
// department (HQ, JC master, JF franchise, suppliers). One row = one login.
//
//   node scripts/export-credentials-pdf.js
// Output: imports/JC-Market-golive-credentials.pdf   (gitignored, mode 600)
//
// Reuses the Playwright/Chromium install in the sibling FoodStory project.

const fs = require('fs');
const path = require('path');
const { chromium } = require('/Users/jiancha/AgenAi_Jiancha/FoodStory/node_modules/playwright');

const CRED = path.join(__dirname, '..', 'imports', 'golive-credentials.json');
const OUT = path.join(__dirname, '..', 'imports', 'JC-Market-golive-credentials.pdf');

if (!fs.existsSync(CRED)) {
  console.error('Missing credentials file — run gen-golive-credentials.js first.');
  process.exit(1);
}
const { users } = JSON.parse(fs.readFileSync(CRED, 'utf8'));

const GROUPS = [
  { key: 'hq',        title: 'HQ / สำนักงานใหญ่', hint: 'Finance · SCM · IT/Admin · CEO' },
  { key: 'branch-jc', title: 'สาขา Master (JC)',   hint: 'บริษัทเป็นเจ้าของ · ไม่ผ่าน Finance · ไม่มีชำระเงิน' },
  { key: 'branch-fc', title: 'สาขาแฟรนไชส์ (JF)',  hint: 'จ่ายผ่านสลิป · ผ่าน Finance' },
  { key: 'supplier',  title: 'Supplier (ของสด)',   hint: 'ผู้ส่งของสด · เห็นเฉพาะ PO ของตัวเอง' },
  { key: 'cti',       title: 'คลัง CTI',            hint: 'จัดของ (warehouse pick) + ขนส่ง (dispatch)' },
];

const ROLE_TH = {
  branch_owner: 'เจ้าของสาขา', supplier: 'ผู้ขาย', finance: 'Finance',
  admin_scm: 'SCM', super_admin: 'Admin', cti: 'คลัง/จัดส่ง',
};
const esc = (s) => String(s == null ? '' : s).replace(/[&<>]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;' }[c]));

function rows(list) {
  return list.map((u) => {
    const scope = u.branch_code || u.vendor_no || '—';
    return `<tr>
      <td class="c">${esc(scope)}</td>
      <td>${esc(u.display_name)}</td>
      <td class="mono">${esc(u.username)}</td>
      <td class="mono pw">${esc(u.password)}</td>
      <td class="c small">${esc(ROLE_TH[u.role] || u.role)}</td>
    </tr>`;
  }).join('');
}

function section(g) {
  const list = users.filter((u) => u.category === g.key);
  if (!list.length) return '';
  return `<section>
    <h2>${esc(g.title)} <span class="cnt">${list.length}</span></h2>
    <p class="hint">${esc(g.hint)}</p>
    <table>
      <thead><tr><th>สาขา/รหัส</th><th>ชื่อ</th><th>Username</th><th>Password</th><th>สิทธิ์</th></tr></thead>
      <tbody>${rows(list)}</tbody>
    </table>
  </section>`;
}

const today = new Date().toISOString().slice(0, 10);
const html = `<!doctype html><html lang="th"><head><meta charset="utf-8">
<link href="https://fonts.googleapis.com/css2?family=Sarabun:wght@400;600;700&family=JetBrains+Mono:wght@600&display=swap" rel="stylesheet">
<style>
  *{box-sizing:border-box}
  body{font-family:'Sarabun',sans-serif;color:#2a2118;font-size:12px;padding:36px 40px;margin:0}
  header{border-bottom:2px solid #AD9C82;padding-bottom:10px;margin-bottom:6px}
  h1{font-size:22px;color:#8a7d66;margin:0}
  .meta{color:#8a7d66;font-size:11px;margin-top:2px}
  .warn{background:#fbf3e4;border:1px solid #e6d3a8;border-radius:6px;padding:8px 12px;margin:12px 0;font-size:11px;color:#7a6320}
  section{margin-top:18px;break-inside:avoid}
  h2{font-size:15px;color:#2a2118;margin:0 0 2px;border-bottom:1px solid #ebe6dd;padding-bottom:4px}
  .cnt{background:#AD9C82;color:#fff;border-radius:10px;font-size:11px;padding:1px 8px;margin-left:6px;vertical-align:middle}
  .hint{color:#8a7d66;font-size:10.5px;margin:2px 0 6px}
  table{width:100%;border-collapse:collapse;font-size:11.5px}
  th{background:#f5efe5;color:#6b5f4a;text-align:left;padding:5px 8px;font-weight:600;border-bottom:1px solid #e0d8c9}
  td{padding:4px 8px;border-bottom:1px solid #f0ebe1}
  td.c{text-align:center}.small{font-size:10.5px;color:#8a7d66}
  .mono{font-family:'JetBrains Mono',monospace}
  .pw{color:#8a3d2a;font-weight:600;letter-spacing:.5px}
  footer{margin-top:22px;color:#a99;font-size:10px;border-top:1px solid #eee;padding-top:8px}
</style></head><body>
  <header>
    <h1>JC-Market — รหัสผู้ใช้งานจริง (Go-live)</h1>
    <div class="meta">ออกเมื่อ ${today} · รวม ${users.length} บัญชี · รหัสผ่าน 6 หลัก (ตัวเลข+สัญลักษณ์)</div>
  </header>
  <div class="warn">เอกสารลับ — แจกให้แต่ละฝ่าย/สาขาเฉพาะแถวของตน แนะนำให้เปลี่ยนรหัสผ่านหลังเข้าใช้ครั้งแรก</div>
  ${GROUPS.map(section).join('')}
  <footer>Generated by scripts/export-credentials-pdf.js · source: imports/golive-credentials.json</footer>
</body></html>`;

(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage();
  await page.setContent(html, { waitUntil: 'networkidle' });
  await page.pdf({ path: OUT, format: 'A4', printBackground: true, margin: { top: '0', bottom: '0', left: '0', right: '0' } });
  await browser.close();
  fs.chmodSync(OUT, 0o600);
  console.log(`Wrote ${path.relative(process.cwd(), OUT)} (${users.length} accounts)`);
})();
